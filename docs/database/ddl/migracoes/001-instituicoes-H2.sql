-- =====================================================================
-- Migração 001 - Instituições (H2)
-- Para bancos que JÁ possuem CV01_USUARIOS e CV02_ROLES.
-- Cria CV03_INSTITUICOES, cria a instituição padrão "ClassVision" e
-- vincula todos os usuários existentes a ela.
-- =====================================================================

CREATE TABLE IF NOT EXISTS PUBLIC.CV03_INSTITUICOES (
    ID             BIGINT NOT NULL AUTO_INCREMENT,
    NOME           CHARACTER VARYING(255) NOT NULL,
    CNPJ           CHARACTER VARYING(14)  NOT NULL,
    TELEFONE       CHARACTER VARYING(20)  NOT NULL,
    SITUACAO       CHARACTER VARYING(20)  NOT NULL,
    CRIADO_EM      TIMESTAMP NOT NULL,
    ATUALIZADO_EM  TIMESTAMP,
    CONSTRAINT PK_CV03_INSTITUICOES PRIMARY KEY (ID),
    CONSTRAINT UK_CV03_INSTITUICOES_CNPJ UNIQUE (CNPJ),
    CONSTRAINT CK_CV03_INSTITUICOES_SITUACAO CHECK (SITUACAO IN ('ATIVA', 'INATIVA'))
);

INSERT INTO PUBLIC.CV03_INSTITUICOES (NOME, CNPJ, TELEFONE, SITUACAO, CRIADO_EM, ATUALIZADO_EM)
SELECT 'ClassVision', '00000000000000', '0000000000', 'ATIVA', CURRENT_TIMESTAMP, CURRENT_TIMESTAMP
WHERE NOT EXISTS (SELECT 1 FROM PUBLIC.CV03_INSTITUICOES WHERE CNPJ = '00000000000000');

ALTER TABLE PUBLIC.CV01_USUARIOS ADD COLUMN IF NOT EXISTS BIGINT_INSTITUICAO_ID BIGINT;

UPDATE PUBLIC.CV01_USUARIOS
   SET BIGINT_INSTITUICAO_ID = (SELECT ID FROM PUBLIC.CV03_INSTITUICOES WHERE CNPJ = '00000000000000')
 WHERE BIGINT_INSTITUICAO_ID IS NULL;

ALTER TABLE PUBLIC.CV01_USUARIOS ALTER COLUMN BIGINT_INSTITUICAO_ID SET NOT NULL;

ALTER TABLE PUBLIC.CV01_USUARIOS ADD CONSTRAINT IF NOT EXISTS FK_CV01_USUARIOS_INSTITUICAO
    FOREIGN KEY (BIGINT_INSTITUICAO_ID) REFERENCES PUBLIC.CV03_INSTITUICOES (ID);

CREATE INDEX IF NOT EXISTS IDX_CV01_USUARIOS_INSTITUICAO ON PUBLIC.CV01_USUARIOS (BIGINT_INSTITUICAO_ID);
